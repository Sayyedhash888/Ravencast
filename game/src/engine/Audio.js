/**
 * Audio.
 *
 * The asset packs ship no sound, so every effect here is synthesised from
 * oscillators and filtered noise. The three music beds (town / fight / boss)
 * are the exception: they are hand-supplied MP3s in `assets/audio/`, played
 * through Web Audio so they can crossfade with the game state and duck under
 * dialogue. They sit deliberately low in the mix.
 *
 * The context is created on the first user gesture (browser autoplay policy),
 * so `init()` must be called from a click/keydown handler.
 */

const MUSIC_TRACKS = {
  town: 'assets/audio/town.mp3',
  combat: 'assets/audio/combat.mp3',
  boss: 'assets/audio/boss.mp3',
};

const MUSIC_VOLUME = 0.08;

// One-shot samples generated by tools/sfx_synth.py. Any of these can be
// replaced with a CC0 sample of the same name without touching the code; if a
// file is missing the matching synth below is used instead.
const SFX_SAMPLES = {
  footstep: [
    'assets/audio/sfx/footstep_1.mp3', 'assets/audio/sfx/footstep_2.mp3',
    'assets/audio/sfx/footstep_3.mp3', 'assets/audio/sfx/footstep_4.mp3',
  ],
  swing: [
    'assets/audio/sfx/swing_1.mp3', 'assets/audio/sfx/swing_2.mp3',
    'assets/audio/sfx/swing_3.mp3',
  ],
  hit: [
    'assets/audio/sfx/hit_1.mp3', 'assets/audio/sfx/hit_2.mp3',
  ],
};

export class Audio {
  constructor() {
    this.ctx = null;
    this.ready = false;
    this.enabled = true;
    this.volume = 0.75;
    this._padTimer = null;
    this._padIndex = 0;

    /** mode -> decoded AudioBuffer */
    this.musicBuffers = {};
    this.musicMode = null;
    this.musicVoice = null;
    this.musicVolume = MUSIC_VOLUME;
    this.musicDucked = false;
    this._musicLoading = false;

    /** name -> decoded one-shot AudioBuffers */
    this.sfxSamples = { footstep: [], swing: [], hit: [] };
    this._sfxLoading = false;
    this._footSide = 1;
  }

  init() {
    if (this.ctx) {
      if (this.ctx.state === 'suspended') this.ctx.resume();
      return;
    }
    const Ctx = window.AudioContext || window.webkitAudioContext;
    if (!Ctx) return;

    const ctx = new Ctx();
    this.ctx = ctx;

    this.master = ctx.createGain();
    this.master.gain.value = this.enabled ? this.volume : 0;
    this.master.connect(ctx.destination);

    // shared reverb so everything sits in the same space
    this.verb = ctx.createConvolver();
    this.verb.buffer = this._impulse(2.4, 2.6);
    this.verbGain = ctx.createGain();
    this.verbGain.gain.value = 0.34;
    this.verb.connect(this.verbGain);
    this.verbGain.connect(this.master);

    this.sfx = ctx.createGain();
    this.sfx.gain.value = 0.9;
    this.sfx.connect(this.master);
    this.sfxSend = ctx.createGain();
    this.sfxSend.gain.value = 0.18;
    this.sfx.connect(this.sfxSend);
    this.sfxSend.connect(this.verb);

    this.amb = ctx.createGain();
    this.amb.gain.value = 0.5;
    this.amb.connect(this.master);

    this._noise = this._makeNoise(2.5);
    this.ready = true;

    this._startWind();
    this._startPad();
    this._loadMusic();
    this._loadSamples();
  }

  setEnabled(on) {
    this.enabled = on;
    if (this.master) {
      this.master.gain.setTargetAtTime(on ? this.volume : 0, this.ctx.currentTime, 0.05);
    }
  }

  toggle() {
    this.setEnabled(!this.enabled);
    return this.enabled;
  }

  // ----------------------------------------------------------------- music

  /** Decode the three beds once; failure just leaves the procedural bed alone. */
  async _loadMusic() {
    if (this._musicLoading) return;
    this._musicLoading = true;
    for (const [mode, url] of Object.entries(MUSIC_TRACKS)) {
      try {
        const res = await fetch(url);
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        const data = await res.arrayBuffer();
        this.musicBuffers[mode] = await this.ctx.decodeAudioData(data);
      } catch (err) {
        console.warn('[Audio] music unavailable:', url, err?.message || err);
      }
    }
    // a mode may have been requested while the files were decoding
    if (this.musicMode) this._playMusic(this.musicMode);
  }

  /**
   * Crossfade to a bed. `mode` is 'town', 'combat', 'boss' or 'none'.
   * Repeated calls with the same mode are free.
   */
  setMusic(mode) {
    if (!this.ready) {
      this.musicMode = mode;
      return;
    }
    if (mode === this.musicMode && (this.musicVoice || !this.musicBuffers[mode])) return;
    this.musicMode = mode;
    if (mode === 'none') {
      this._fadeOutMusic();
      return;
    }
    this._playMusic(mode);
  }

  /** Duck the bed under dialogue or a full-screen panel. */
  setMusicDuck(on) {
    if (on === this.musicDucked) return;
    this.musicDucked = on;
    if (!this.musicVoice || !this.ready) return;
    const level = on ? this.musicVolume * 0.4 : this.musicVolume;
    this.musicVoice.gain.gain.setTargetAtTime(level, this.ctx.currentTime, 0.3);
  }

  _playMusic(mode) {
    const buffer = this.musicBuffers[mode];
    if (!buffer) return;

    const ctx = this.ctx;
    const t = ctx.currentTime;
    const src = ctx.createBufferSource();
    src.buffer = buffer;
    src.loop = true;

    const gain = ctx.createGain();
    gain.gain.setValueAtTime(0.0001, t);
    gain.gain.exponentialRampToValueAtTime(
      this.musicDucked ? this.musicVolume * 0.4 : this.musicVolume, t + 1.6,
    );
    src.connect(gain).connect(this.master);
    src.start(t);

    const previous = this.musicVoice;
    this.musicVoice = { src, gain };

    if (previous) {
      previous.gain.gain.cancelScheduledValues(t);
      previous.gain.gain.setValueAtTime(Math.max(previous.gain.gain.value, 0.0001), t);
      previous.gain.gain.exponentialRampToValueAtTime(0.0001, t + 1.2);
      setTimeout(() => { try { previous.src.stop(); } catch { /* already stopped */ } }, 1400);
    }

    // give the music room: the wind and drone step back while a bed plays
    this.amb?.gain.setTargetAtTime(0.18, t, 1.5);
  }

  _fadeOutMusic() {
    const voice = this.musicVoice;
    if (!voice) return;
    this.musicVoice = null;
    const t = this.ctx.currentTime;
    voice.gain.gain.cancelScheduledValues(t);
    voice.gain.gain.setValueAtTime(Math.max(voice.gain.gain.value, 0.0001), t);
    voice.gain.gain.exponentialRampToValueAtTime(0.0001, t + 1.2);
    setTimeout(() => { try { voice.src.stop(); } catch { /* already stopped */ } }, 1400);
    this.amb?.gain.setTargetAtTime(0.5, t, 1.5);
  }

  // ------------------------------------------------------------ one-shots

  /** Decode the generated footstep / swing / hit samples, once. */
  async _loadSamples() {
    if (this._sfxLoading) return;
    this._sfxLoading = true;
    await Promise.all(Object.entries(SFX_SAMPLES).map(async ([name, urls]) => {
      const buffers = [];
      for (const url of urls) {
        try {
          const res = await fetch(url);
          if (!res.ok) continue;
          buffers.push(await this.ctx.decodeAudioData(await res.arrayBuffer()));
        } catch { /* keep the synthesised fallback */ }
      }
      this.sfxSamples[name] = buffers;
    }));
  }

  /** Play a decoded one-shot; returns false when no sample is available. */
  _playSample(name, { gain = 0.5, rate = 1, pan = 0, variant = null, send = 0 } = {}) {
    const list = this.sfxSamples[name];
    if (!this.ready || !list || list.length === 0) return false;

    const buffer = variant != null && list[variant]
      ? list[variant]
      : list[Math.floor(Math.random() * list.length)];
    const ctx = this.ctx;
    const src = ctx.createBufferSource();
    src.buffer = buffer;
    src.playbackRate.value = rate;

    const g = ctx.createGain();
    g.gain.value = gain;
    src.connect(g);

    let tail = g;
    if (pan && ctx.createStereoPanner) {
      const p = ctx.createStereoPanner();
      p.pan.value = Math.max(-1, Math.min(1, pan));
      g.connect(p);
      tail = p;
    }
    tail.connect(this.sfx);
    if (send > 0) {
      const s = ctx.createGain();
      s.gain.value = send;
      tail.connect(s).connect(this.verb);
    }
    src.start();
    return true;
  }

  // ------------------------------------------------------------- primitives

  _makeNoise(seconds) {
    const ctx = this.ctx;
    const len = Math.floor(ctx.sampleRate * seconds);
    const buf = ctx.createBuffer(1, len, ctx.sampleRate);
    const d = buf.getChannelData(0);
    for (let i = 0; i < len; i++) d[i] = Math.random() * 2 - 1;
    return buf;
  }

  _impulse(seconds, decay) {
    const ctx = this.ctx;
    const len = Math.floor(ctx.sampleRate * seconds);
    const buf = ctx.createBuffer(2, len, ctx.sampleRate);
    for (let c = 0; c < 2; c++) {
      const d = buf.getChannelData(c);
      for (let i = 0; i < len; i++) {
        d[i] = (Math.random() * 2 - 1) * Math.pow(1 - i / len, decay);
      }
    }
    return buf;
  }

  _noiseSource(playbackRate = 1) {
    const src = this.ctx.createBufferSource();
    src.buffer = this._noise;
    src.loop = true;
    src.playbackRate.value = playbackRate;
    // random start so repeated effects never sound identical
    src._offset = Math.random() * this._noise.duration;
    return src;
  }

  /** Exponential-ish decay envelope on a gain node. */
  _env(peak, attack, hold, release, t0) {
    const g = this.ctx.createGain();
    g.gain.setValueAtTime(0.0001, t0);
    g.gain.exponentialRampToValueAtTime(Math.max(peak, 0.0002), t0 + attack);
    if (hold > 0) g.gain.setValueAtTime(Math.max(peak, 0.0002), t0 + attack + hold);
    g.gain.exponentialRampToValueAtTime(0.0001, t0 + attack + hold + release);
    return g;
  }

  _osc(type, freq, t0, dur) {
    const o = this.ctx.createOscillator();
    o.type = type;
    o.frequency.setValueAtTime(freq, t0);
    o.start(t0);
    o.stop(t0 + dur + 0.05);
    return o;
  }

  // ------------------------------------------------------------------- sfx

  swing(power = 1) {
    if (!this.ready) return;
    if (this._playSample('swing', {
      gain: 0.45 * power,
      rate: 0.95 + Math.random() * 0.1,
      pan: (Math.random() - 0.5) * 0.3,
      send: 0.08,
    })) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;

    const src = this._noiseSource(1);
    const bp = ctx.createBiquadFilter();
    bp.type = 'bandpass';
    bp.Q.value = 1.1;
    bp.frequency.setValueAtTime(1900 * power, t0);
    bp.frequency.exponentialRampToValueAtTime(360, t0 + 0.24);

    const g = this._env(0.16 * power, 0.012, 0, 0.2, t0);
    src.connect(bp).connect(g).connect(this.sfx);
    src.start(t0, src._offset);
    src.stop(t0 + 0.3);

    // a low "air" layer gives the blade some weight
    const air = this._osc('sine', 300 * power, t0, 0.22);
    air.frequency.exponentialRampToValueAtTime(110, t0 + 0.2);
    const ag = this._env(0.06 * power, 0.01, 0, 0.19, t0);
    air.connect(ag).connect(this.sfx);
  }

  hit(heavy = false) {
    if (!this.ready) return;
    if (this._playSample('hit', {
      gain: heavy ? 0.8 : 0.62,
      rate: heavy ? 0.92 : 1 + Math.random() * 0.06,
      variant: heavy ? 1 : 0,
      send: 0.14,
    })) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;

    const body = this._osc('sine', heavy ? 150 : 190, t0, heavy ? 0.34 : 0.18);
    body.frequency.exponentialRampToValueAtTime(heavy ? 42 : 58, t0 + (heavy ? 0.3 : 0.16));
    const bg = this._env(heavy ? 0.42 : 0.3, 0.004, 0, heavy ? 0.3 : 0.16, t0);
    body.connect(bg).connect(this.sfx);

    const src = this._noiseSource(1);
    const hp = ctx.createBiquadFilter();
    hp.type = 'highpass';
    hp.frequency.value = heavy ? 900 : 1400;
    const ng = this._env(heavy ? 0.2 : 0.14, 0.002, 0, 0.07, t0);
    src.connect(hp).connect(ng).connect(this.sfx);
    src.start(t0, src._offset);
    src.stop(t0 + 0.12);
  }

  block() {
    if (!this.ready) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;

    [2350, 3480].forEach((f, i) => {
      const o = this._osc('triangle', f, t0, 0.16);
      const g = this._env(0.1 - i * 0.03, 0.002, 0, 0.15, t0);
      o.connect(g).connect(this.sfx);
    });

    const src = this._noiseSource(1);
    const lp = ctx.createBiquadFilter();
    lp.type = 'lowpass';
    lp.frequency.value = 520;
    const g = this._env(0.2, 0.003, 0, 0.1, t0);
    src.connect(lp).connect(g).connect(this.sfx);
    src.start(t0, src._offset);
    src.stop(t0 + 0.16);
  }

  playerHurt() {
    if (!this.ready) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;

    const o = this._osc('sawtooth', 210, t0, 0.3);
    o.frequency.exponentialRampToValueAtTime(88, t0 + 0.26);
    const lp = ctx.createBiquadFilter();
    lp.type = 'lowpass';
    lp.frequency.setValueAtTime(1100, t0);
    lp.frequency.exponentialRampToValueAtTime(340, t0 + 0.26);
    const g = this._env(0.26, 0.006, 0, 0.26, t0);
    o.connect(lp).connect(g).connect(this.sfx);

    const src = this._noiseSource(0.8);
    const ng = this._env(0.14, 0.004, 0, 0.14, t0);
    src.connect(ng).connect(this.sfx);
    src.start(t0, src._offset);
    src.stop(t0 + 0.2);
  }

  enemyDeath(big = false) {
    if (!this.ready) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;

    const o = this._osc('sawtooth', big ? 190 : 265, t0, 0.6);
    o.frequency.exponentialRampToValueAtTime(big ? 38 : 62, t0 + 0.5);
    const lp = ctx.createBiquadFilter();
    lp.type = 'lowpass';
    lp.frequency.setValueAtTime(1500, t0);
    lp.frequency.exponentialRampToValueAtTime(240, t0 + 0.5);
    const g = this._env(big ? 0.34 : 0.24, 0.008, 0, 0.5, t0);
    o.connect(lp).connect(g).connect(this.sfx);

    const src = this._noiseSource(0.7);
    const bp = ctx.createBiquadFilter();
    bp.type = 'bandpass';
    bp.frequency.setValueAtTime(700, t0);
    bp.frequency.exponentialRampToValueAtTime(180, t0 + 0.45);
    bp.Q.value = 0.8;
    const ng = this._env(0.18, 0.01, 0, 0.42, t0);
    src.connect(bp).connect(ng).connect(this.sfx);
    src.start(t0, src._offset);
    src.stop(t0 + 0.55);
  }

  footstep(power = 1) {
    if (!this.ready) return;
    const pan = (this._footSide = -this._footSide) * 0.12;
    if (this._playSample('footstep', {
      gain: 0.18 * power,
      rate: 0.95 + Math.random() * 0.1,
      pan,
      send: 0.04,
    })) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;
    const src = this._noiseSource(0.8 + Math.random() * 0.5);
    const lp = ctx.createBiquadFilter();
    lp.type = 'lowpass';
    lp.frequency.value = 340 + Math.random() * 160;
    const g = this._env(0.03 * power, 0.004, 0, 0.07, t0);
    src.connect(lp).connect(g).connect(this.sfx);
    src.start(t0, src._offset);
    src.stop(t0 + 0.12);
  }

  dodge() {
    if (!this.ready) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;
    const src = this._noiseSource(1.1);
    const bp = ctx.createBiquadFilter();
    bp.type = 'bandpass';
    bp.Q.value = 0.9;
    bp.frequency.setValueAtTime(420, t0);
    bp.frequency.exponentialRampToValueAtTime(2100, t0 + 0.26);
    const g = this._env(0.13, 0.03, 0, 0.24, t0);
    src.connect(bp).connect(g).connect(this.sfx);
    src.start(t0, src._offset);
    src.stop(t0 + 0.32);
  }

  waveHorn() {
    if (!this.ready) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;
    const lp = ctx.createBiquadFilter();
    lp.type = 'lowpass';
    lp.frequency.setValueAtTime(500, t0);
    lp.frequency.linearRampToValueAtTime(1400, t0 + 0.7);
    lp.frequency.linearRampToValueAtTime(700, t0 + 1.6);
    const g = this._env(0.19, 0.35, 0.4, 0.8, t0);
    lp.connect(g).connect(this.sfx);

    [[110, 0], [164.8, 4], [220, -5]].forEach(([f, detune]) => {
      const o = this._osc('sawtooth', f, t0, 1.7);
      o.detune.value = detune;
      o.connect(lp);
    });
  }

  waveClear() {
    if (!this.ready) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;
    [523.25, 659.25, 783.99, 1046.5].forEach((f, i) => {
      const o = this._osc('sine', f, t0 + i * 0.09, 0.6);
      const g = this._env(0.1, 0.01, 0, 0.5, t0 + i * 0.09);
      o.connect(g).connect(this.sfx);
    });
  }

  uiClick() {
    if (!this.ready) return;
    const ctx = this.ctx;
    const t0 = ctx.currentTime;
    const o = this._osc('sine', 660, t0, 0.09);
    const g = this._env(0.09, 0.003, 0, 0.08, t0);
    o.connect(g).connect(this.sfx);
  }

  // -------------------------------------------------------------- ambience

  _startWind() {
    const ctx = this.ctx;

    // slow-breathing low wind
    const src = this._noiseSource(0.5);
    const lp = ctx.createBiquadFilter();
    lp.type = 'lowpass';
    lp.frequency.value = 380;
    lp.Q.value = 0.6;
    const g = ctx.createGain();
    g.gain.value = 0.075;
    src.connect(lp).connect(g).connect(this.amb);
    src.start(0, src._offset);

    // LFO drifting the cutoff so the wind rises and falls
    const lfo = ctx.createOscillator();
    lfo.type = 'sine';
    lfo.frequency.value = 0.055;
    const lfoGain = ctx.createGain();
    lfoGain.gain.value = 190;
    lfo.connect(lfoGain).connect(lp.frequency);
    lfo.start();

    // a brighter rustle layer for the canopy
    const src2 = this._noiseSource(0.9);
    const bp = ctx.createBiquadFilter();
    bp.type = 'bandpass';
    bp.frequency.value = 1050;
    bp.Q.value = 0.5;
    const g2 = ctx.createGain();
    g2.gain.value = 0.022;
    src2.connect(bp).connect(g2).connect(this.amb);
    src2.start(0, src2._offset);

    const lfo2 = ctx.createOscillator();
    lfo2.type = 'sine';
    lfo2.frequency.value = 0.083;
    const lfo2Gain = ctx.createGain();
    lfo2Gain.gain.value = 0.016;
    lfo2.connect(lfo2Gain).connect(g2.gain);
    lfo2.start();
  }

  _startPad() {
    // slow modal drone; shifts chord every ~14s so it never loops audibly
    const chords = [
      [55.0, 82.41, 130.81],
      [49.0, 73.42, 116.54],
      [61.74, 92.50, 146.83],
      [43.65, 65.41, 103.83],
    ];

    const play = () => {
      if (!this.ready) return;
      const ctx = this.ctx;
      const t0 = ctx.currentTime;
      const notes = chords[this._padIndex % chords.length];
      this._padIndex++;

      const lp = ctx.createBiquadFilter();
      lp.type = 'lowpass';
      lp.frequency.setValueAtTime(300, t0);
      lp.frequency.linearRampToValueAtTime(520, t0 + 6);
      lp.frequency.linearRampToValueAtTime(280, t0 + 14);
      const g = ctx.createGain();
      g.gain.setValueAtTime(0.0001, t0);
      g.gain.linearRampToValueAtTime(0.05, t0 + 4);
      g.gain.linearRampToValueAtTime(0.0001, t0 + 14);
      lp.connect(g).connect(this.amb);

      notes.forEach((f, i) => {
        const o = ctx.createOscillator();
        o.type = i === 0 ? 'sine' : 'triangle';
        o.frequency.value = f;
        o.detune.value = (i - 1) * 6;
        const og = ctx.createGain();
        og.gain.value = i === 0 ? 1 : 0.4;
        o.connect(og).connect(lp);
        o.start(t0);
        o.stop(t0 + 14.4);
      });

      this._padTimer = setTimeout(play, 14000);
    };

    play();
  }

  dispose() {
    clearTimeout(this._padTimer);
    try { this.musicVoice?.src.stop(); } catch { /* ignore */ }
    this.ctx?.close();
  }
}
